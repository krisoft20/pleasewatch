import { writable, derived, get, type Readable } from 'svelte/store';

export type Lang = 'EN' | 'PL' | 'DE';

export const LANGS: Array<{ code: Lang; country: string; name: string }> = [
    { code: 'EN', country: 'GB', name: 'English' },
    { code: 'PL', country: 'PL', name: 'Polski' },
    { code: 'DE', country: 'DE', name: 'Deutsch' }
];

export function subLangCode(code: Lang): string {
    return ({ EN: 'eng', PL: 'pol', DE: 'ger' } as const)[code];
}

export function flagEmoji(country: string): string {
    return country.toUpperCase().replace(/./g, (c) => String.fromCodePoint(127397 + c.charCodeAt(0)));
}

const STORAGE_KEY = 'pw-lang';

function readSaved(): Lang {
    if (typeof localStorage === 'undefined') return 'EN';
    const v = localStorage.getItem(STORAGE_KEY);
    if (v === 'EN' || v === 'PL' || v === 'DE') return v;
    return 'EN';
}

export const lang = writable<Lang>(readSaved());
lang.subscribe((v) => {
    if (typeof localStorage !== 'undefined') {
        try {
            localStorage.setItem(STORAGE_KEY, v);
        } catch {}
    }
});

export function currentLang(): Lang {
    return get(lang);
}
export function setLang(code: Lang) {
    lang.set(code);
}

